'''
From a .csv generated by expstats_attention_init_recompute, reads it, convert it in a dataframe

and plots the histogramm of the chosen quantity, passed as args with respect to hidden dimension.
'''




from compute_ranks import _read_df, _METHOD_SPECS
import argparse
import pandas as pd
import matplotlib.pyplot as plt

def plot_histograms(df, bins=30, quantity='rank_full', x_label='rank', output=None):

    hidden_dims = sorted(df["hidden_dim"].unique())

    colors = plt.cm.viridis(
        [i / max(len(hidden_dims) - 1, 1) for i in range(len(hidden_dims))]
    )

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))

    # Left: at critical
    data_rank = [
        df.loc[df["hidden_dim"] == h, quantity].dropna()
        for h in hidden_dims
    ]

    axes[0].hist(
        data_rank,
        bins=bins,
        stacked=True,
        color=colors,
        label=[f"hidden_dim={h}" for h in hidden_dims],
        alpha=0.8,
    )
    axes[0].set_title("At critical point")
    axes[0].set_xlabel(x_label)
    axes[0].set_ylabel("Count")
    axes[0].legend()

    # Right: at initialisation
    data_init = [
        df.loc[df["hidden_dim"] == h, "init_"+quantity].dropna()
        for h in hidden_dims
    ]

    axes[1].hist(
        data_init,
        bins=bins,
        stacked=True,
        color=colors,
        label=[f"hidden_dim={h}" for h in hidden_dims],
        alpha=0.8,
    )
    axes[1].set_title("At initialisation")
    axes[1].set_xlabel(x_label)
    axes[1].set_ylabel("Count")
    axes[1].legend()

    plt.tight_layout()
    fig.suptitle(f"Histogramm of {quantity} for $n_1$={hidden_dims}.")

    if output:
        plt.savefig(output, dpi=300, bbox_inches="tight")
    else:
        plt.show()


def main():
    parser = argparse.ArgumentParser(
        description="Plot stacked rank histograms grouped by hidden_dim."
    )

    parser.add_argument("--input",type=str,required=True,help="Path to input CSV file.")

    parser.add_argument("--bins",type=int,default=30,help="Number of histogram bins (default: 30).")

    parser.add_argument("--output",type=str,default=None,help="Optional path to save the figure.")

    parser.add_argument("--quantity",type=str, default='rank_full',choices=['rank_full','num_distinct_pat','pattern_rank','rank_rho','rank_rest'],help='which quantity to plot the histogramm')

    parser.add_argument("--rank_method",type=str,default=None, help='rank_method used to generate the csv, if none infered from input path')
    args = parser.parse_args()

    df = _read_df(args.input)
    rank_method=(args.dataframe_path.split('__')[-1]).split('.')[0] if args.rank_method is None else args.rank_method
    suffix='' if rank_method=='float64' else rank_method
    required_columns = {"hidden_dim", args.quantity+suffix, "init_"+args.quantity+suffix,}
    
    missing = required_columns - set(df.columns)

    if missing:
        raise ValueError(f"Missing required columns: {missing}, is the rank_method correct?")
    suffix='' if args.rank_method=='float64' else args.rank_method

    x_labels={'rank_full'+suffix: rf"$\mathrm{{rank}}\mathbf{{D}}f(\theta,X)$",
              'rank_rho'+suffix: rf"$\mathrm{{rank}}J_{{\theta_f}}$",
              'rank_rest'+suffix: rf"$\mathrm{{rank}}J_{{rest}}$",
            'pattern_rank'+suffix:rf"$\mathrm{{rank}}(D)$",
            'num_distinct_pat'+suffix:rf"$|\mathcal{{A}}(\theta,X)|$"}

    plot_histograms(df, bins=args.bins,quantity=args.quantity+suffix, x_label=x_labels[args.quantity+suffix], output=args.output)


if __name__ == "__main__":
    main()
