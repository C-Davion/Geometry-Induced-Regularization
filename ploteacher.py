'''
Plots the teacher function (true Y) by reading the .jsonl file generated by the teacherfunction.py
requires prior knowledge of the feature transformation (rho) used to construct the teacher function, as well as the general shape of the function
'''


import numpy as np
import matplotlib.pyplot as plt
import json


LOG_FILE = "interesting_functions.jsonl"

def rho(x):
    x = np.asarray(x)
    return np.vstack((np.ones_like(x), x, x**2))


def f(A, A1, B, B1, x):
    X = rho(x)

    Ax = A @ X
    A1x = A1 @ X
    Bx = B @ X
    B1x = B1 @ X

    mA = np.minimum(Ax, A1x)
    mB = np.minimum(Bx, B1x)

    y = np.maximum(mA, mB)

    return y, Ax, A1x, Bx, B1x



if __name__ == "__main__":
    x=np.linspace(-2,2,500)

    with open (LOG_FILE) as file:
        for line in file:
            r=json.loads(line)
            A=np.array(r["A"])
            A1=np.array(r["A1"])
            B=np.array(r["B"])
            B1=np.array(r["B1"])

            y, Ax, A1x, Bx, B1x = f(A, A1, B, B1, x)

            use_A = np.minimum(Ax, A1x) >= np.minimum(Bx, B1x)

            labels = np.empty(len(x), dtype=int)
            labels[use_A & (Ax <= A1x)] = 0
            labels[use_A & (Ax > A1x)] = 1
            labels[~use_A & (Bx <= B1x)] = 2
            labels[~use_A & (Bx > B1x)] = 3
            plt.figure(figsize=(7,4))

            plt.plot(x, np.where(labels==0, y, np.nan), lw=3, label="A")
            plt.plot(x, np.where(labels==1, y, np.nan), lw=3, label="A1")
            plt.plot(x, np.where(labels==2, y, np.nan), lw=3, label="B")
            plt.plot(x, np.where(labels==3, y, np.nan), lw=3, label="B1")

            plt.title("teacher_function")
            plt.legend()
            plt.show()
    print('All ploted')
